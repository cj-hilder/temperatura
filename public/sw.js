/* ============================================================================
 * Temperatura — Service Worker  (sw.js)
 *
 * Two jobs:
 *
 *  1. Offline app shell. Cache the shell + assets so the app launches with no
 *     network. Strategy: cache-first for the shell, network-first for the HTML
 *     document so a fresh deploy is picked up immediately.
 *
 *  2. Alarm notifications while the app is hidden. Unlike a typical PWA alert
 *     (Manawa Pace's: auto-closes after a few seconds, no interaction path),
 *     an unsilenced alarm here represents a condition that persists until the
 *     user deals with it — requireInteraction: true, no auto-close timer, and
 *     a notificationclick handler so Silence (or, once an alarm has gone
 *     missed — sounded past its theme's "Silence after" with no response —
 *     Dismiss) works from the lock screen. Tags are composite
 *     (`${instanceId}:${alarmId}`, see engine.js) so several alarms across
 *     several running instances each get their own notification and can be
 *     resolved independently.
 * ========================================================================== */

// Build id is generated by generate-env.mjs into build-id.js on every build
// (see that file for why: no GitHub Actions step exists here to stamp it the
// way Ride the Wind's does). When the bundle changes, the id changes, so old
// shells are purged automatically on activate.
importScripts("./build-id.js");
const VERSION = (self.__TEMPERATURA_BUILD_ID__ || "dev");
const SHELL_CACHE = "temperatura-shell-" + VERSION;

// Paths are relative to the SW's scope. BASE is derived dynamically so the SW
// works at any path (just "/" here, since this is served from the root).
const BASE = new URL("./", self.location).pathname;
// Only pre-cache things whose URL never changes. NOT index.html — that is
// fetched network-first so new deploys are picked up immediately.
const SHELL_ASSETS = [
  BASE + "manifest.webmanifest",
  BASE + "icons/icon-192.png",
  BASE + "icons/icon-512.png",
];

/* ---- install: pre-cache stable assets, then take over immediately ---- */
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE).then((c) => c.addAll(SHELL_ASSETS)).then(() => self.skipWaiting())
  );
});

/* ---- activate: drop ALL old shell caches (any version != current) ---- */
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((k) => k !== SHELL_CACHE)
          .map((k) => caches.delete(k))
      )
    ).then(() => self.clients.claim())
  );
});

/* ---- fetch routing ---- */
self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== "GET") return;

  if (url.origin === self.location.origin) {
    // The HTML document / SPA navigations: NETWORK-FIRST so a fresh deploy is
    // seen at once; fall back to the cached shell only when offline.
    if (event.request.mode === "navigate" || url.pathname === BASE || url.pathname === BASE + "index.html") {
      event.respondWith(networkFirstDoc(event.request));
      return;
    }
    // Hashed build assets (app-a1b2c3.js, *.css): safe to cache-first forever,
    // because Vite changes the filename when the content changes.
    event.respondWith(cacheFirst(event.request));
    return;
  }
  // Everything else: straight to network.
});

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  try {
    const res = await fetch(request);
    if (res.ok) {
      const cache = await caches.open(SHELL_CACHE);
      cache.put(request, res.clone());
    }
    return res;
  } catch {
    throw new Error("offline and uncached");
  }
}

// Network-first for the document: always fetch fresh, cache the latest copy,
// fall back to whatever we last cached if the network is down.
async function networkFirstDoc(request) {
  const cache = await caches.open(SHELL_CACHE);
  try {
    const res = await fetch(request, { cache: "no-store" });
    if (res.ok) cache.put(BASE + "index.html", res.clone());
    return res;
  } catch {
    const cached = await cache.match(BASE + "index.html");
    if (cached) return cached;
    throw new Error("offline and no cached shell");
  }
}

/* ---- message channel: version update + alarm notifications ---- */
self.addEventListener("message", (event) => {
  const msg = event.data || {};
  if (msg.type === "SKIP_WAITING") {
    self.skipWaiting();
    return;
  }
  if (msg.type === "ALARM_NOTIFY") {
    const { tag, title, body, vibrate, canExtend, missed } = msg;
    // A missed alarm has nothing sounding to silence — its primary action is
    // Dismiss instead. `data.missed` is stamped on the notification itself
    // (not just carried in this message) so notificationclick, which only
    // sees the notification object, can tell a bare body-tap on an
    // already-missed notification apart from one on a still-sounding alarm.
    const actions = [{ action: missed ? "dismiss" : "silence", title: missed ? "Dismiss" : "Silence" }];
    // Only a duration-reached alarm offers Extend — engine.js only ever sets
    // canExtend true for that one alarm kind.
    if (canExtend) actions.push({ action: "extend", title: "Extend" });
    event.waitUntil(
      self.registration.showNotification(title, {
        body,
        tag,
        vibrate: vibrate || [],
        renotify: true, // without this, replacing a same-tag notification is silent —
                         // no re-vibrate — which would defeat the whole 5s re-post loop
        requireInteraction: true, // persists until silenced/dismissed — not a transient cue
        actions,
        data: { missed: !!missed },
      })
    );
    return;
  }
  if (msg.type === "ALARM_SILENCE_ACK") {
    // Covers silencing in-app (visible) after a notification was already
    // posted from an earlier hidden spell — nothing left to silence via
    // notificationclick, so the client tells the SW directly to close it.
    const { tag } = msg;
    event.waitUntil(
      self.registration.getNotifications({ tag }).then((ns) => ns.forEach((n) => n.close()))
    );
  }
});

/* ---- notification interaction ----
 * Per spec, tapping the Silence action or the notification body both count
 * as silencing, and tapping the Dismiss action or the body of an
 * already-missed notification both count as dismissing — there's no
 * "just close it without resolving the alarm" path, matching the
 * thermometer button and in-app controls, which are equally unconditional.
 * `event.notification.data.missed` (stamped at post time, see ALARM_NOTIFY
 * above) is what tells a bare body-tap which of the two a given notification
 * means, since a body-tap carries no `event.action` of its own. The Extend
 * action (only ever present on a duration-reached alarm's notification) is
 * the one exception to both: it resolves via the client's own requestExtend
 * flow instead (already missed-aware there), and additionally needs a
 * client window brought forward, since the whole point is for the user to
 * see and answer the "how much time" dialog it opens. */
self.addEventListener("notificationclick", (event) => {
  const tag = event.notification.tag;
  const isMissed = !!event.notification.data?.missed;
  const wantsExtend = event.action === "extend";
  const wantsDismiss = event.action === "dismiss" || (event.action === "" && isMissed);
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clientList) => {
      const messageType = wantsExtend ? "ALARM_EXTEND_REQUESTED" : wantsDismiss ? "ALARM_DISMISSED" : "ALARM_SILENCED";
      clientList.forEach((client) => client.postMessage({ type: messageType, tag }));
      if (wantsExtend) {
        if (clientList.length > 0) clientList[0].focus();
        else if (self.clients.openWindow) self.clients.openWindow(BASE);
      }
    })
  );
});
